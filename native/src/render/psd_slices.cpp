std::string text_of(d::Bytes& b) { return psd::utf8_of(d::read_unicode(b)); }

void put_text(std::string& out, std::string_view utf8) { d::put_unicode(out, psd::utf16(utf8)); }

std::optional<double> number(const d::Object& o, std::string_view key) {
    const d::Value* v = o.get(key);
    return v != nullptr ? v->numeric() : std::nullopt;
}

std::string text(const d::Object& o, std::string_view key) {
    const d::Value* v = o.get(key);
    return v != nullptr && v->type == "TEXT" ? psd::utf8_of(v->text) : std::string();
}

std::optional<std::string> enumerated(const d::Object& o, std::string_view key) {
    const d::Value* v = o.get(key);
    if (v == nullptr || v->type != "enum") return std::nullopt;
    return v->enum_value;
}

std::int32_t clamp32(double v) {
    if (!std::isfinite(v)) return 0;
    return static_cast<std::int32_t>(std::clamp(v, -2147483648.0, 2147483647.0));
}

// top, left, bottom, right
std::optional<std::array<std::int32_t, 4>> bounds_of(const d::Object& o, std::string_view key) {
    const d::Value* v = o.get(key);
    if (v == nullptr || !v->object) return std::nullopt;
    const auto g = [&](std::string_view k) { return clamp32(number(*v->object, k).value_or(0)); };
    return std::array<std::int32_t, 4>{g("Top "), g("Left"), g("Btom"), g("Rght")};
}

std::uint32_t origin_from(const std::string& s) {
    if (s == "autoGenerated") return 0;
    if (s == "layerGenerated" || s == "layer") return 1;
    return 2;
}

std::uint32_t kind_from(const std::string& s) {
    if (s == "noImage") return 0;
    if (s == "Tbl " || s == "table") return 2;
    return 1;
}

FileSlice slice_from(const d::Object& o) {
    FileSlice s;
    s.id = static_cast<std::int64_t>(number(o, "sliceID").value_or(0));
    s.group_id = static_cast<std::uint32_t>(std::max(0.0, number(o, "groupID").value_or(0)));
    s.origin = enumerated(o, "origin") ? origin_from(*enumerated(o, "origin")) : 2;
    if (const auto l = number(o, "layerID")) s.layer_id = static_cast<std::uint32_t>(std::max(0.0, *l));
    s.name = text(o, "Nm  ");
    s.kind = enumerated(o, "Type") ? kind_from(*enumerated(o, "Type")) : 1;
    const auto b = bounds_of(o, "bounds").value_or(std::array<std::int32_t, 4>{});
    s.rect = {b[1], b[0], b[3], b[2]};  // (the descriptor's top, left, bottom, right; the records' left, top, right, bottom)
    s.url = text(o, "url");
    s.target = text(o, "null");
    s.message = text(o, "Msge");
    s.alt = text(o, "altTag");
    if (const d::Value* v = o.get("cellTextIsHTML"); v != nullptr && v->type == "bool") s.cell_text_is_html = v->boolean;
    s.cell_text = text(o, "cellText");
    if (enumerated(o, "bgColorType") == std::optional<std::string>("Clr ")) {
        if (const d::Value* c = o.get("bgColor"); c != nullptr && c->object) {
            const auto g = [&](std::string_view k) { return static_cast<std::uint8_t>(std::clamp(number(*c->object, k).value_or(0), 0.0, 255.0)); };
            s.color = {c->object->get("alpha") != nullptr ? g("alpha") : std::uint8_t(255), g("Rd  "), g("Grn "), g("Bl  ")};
        }
    }
    s.outsets = {clamp32(number(o, "topOutset").value_or(0)), clamp32(number(o, "leftOutset").value_or(0)),
                 clamp32(number(o, "bottomOutset").value_or(0)), clamp32(number(o, "rightOutset").value_or(0))};
    return s;
}

std::vector<FileSlice> listed(const d::Object& top) {
    std::vector<FileSlice> out;
    const d::Value* list = top.get("slices");
    if (list == nullptr || list->type != "VlLs") return out;
    for (const d::Value& item : list->list) {
        if (!item.object) continue;
        if (out.size() >= kSlicesMost) throw d::Broken("too many slices");
        out.push_back(slice_from(*item.object));
    }
    return out;
}

FileSlices read_v6(d::Bytes& b) {
    FileSlices out;
    out.version = 6;
    for (std::int32_t& v : out.bounds) v = b.i32();
    out.group = text_of(b);
    const std::uint32_t n = b.u32();
    if (n > kSlicesMost || n > b.left() / 16) throw d::Broken("too many slices");
    for (std::uint32_t i = 0; i < n; ++i) {
        FileSlice s;
        s.id = b.u32();
        s.group_id = b.u32();
        s.origin = b.u32();
        if (s.origin == 1) s.layer_id = b.u32();
        s.name = text_of(b);
        s.kind = b.u32();
        for (std::int32_t& v : s.rect) v = b.i32();
        s.url = text_of(b);
        s.target = text_of(b);
        s.message = text_of(b);
        s.alt = text_of(b);
        s.cell_text_is_html = b.u8() != 0;
        s.cell_text = text_of(b);
        s.horizontal_align = b.u32();
        s.vertical_align = b.u32();
        for (std::uint8_t& c : s.color) c = static_cast<std::uint8_t>(b.u8());
        out.slices.push_back(std::move(s));
    }
    return out;
}

