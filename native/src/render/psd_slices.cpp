std::optional<FileSlices> parse(std::string_view data) {
    try {
        d::Bytes b(data);
        const std::uint32_t version = b.u32();
        if (version == 6) {
            FileSlices out = read_v6(b);
            // (Photoshop 7 and later: a descriptor after, each slice's extras — the outsets; a broken one passed over, as upstream)
            if (b.left() >= 4) {
                try {
                    const d::Object extra = d::read_versioned(data, b.at());
                    for (const FileSlice& e : listed(extra)) {
                        for (FileSlice& s : out.slices)
                            if (s.id == e.id) s.outsets = e.outsets;
                    }
                } catch (const std::exception&) {  // (a broken tail: the slices as they are)
                }
            }
            return out;
        }
        if (version == 7 || version == 8) {
            const d::Object top = d::read_versioned(data, b.at());
            FileSlices out;
            out.version = version;
            out.bounds = bounds_of(top, "bounds").value_or(std::array<std::int32_t, 4>{});
            out.group = text(top, "baseName");
            out.slices = listed(top);
            return out;
        }
        return std::nullopt;
    } catch (const std::exception&) {
        return std::nullopt;
    }
}

std::string resource(const FileSlices& slices) {
    std::string out;
    d::put_u32(out, 6);
    for (const std::int32_t v : slices.bounds) d::put_i32(out, v);
    put_text(out, slices.group);
    d::put_u32(out, static_cast<std::uint32_t>(slices.slices.size()));
    for (const FileSlice& s : slices.slices) {
        d::put_u32(out, static_cast<std::uint32_t>(s.id));
        d::put_u32(out, s.group_id);
        d::put_u32(out, s.origin);
        if (s.origin == 1) d::put_u32(out, s.layer_id.value_or(0));
        put_text(out, s.name);
        d::put_u32(out, s.kind);
        for (const std::int32_t v : s.rect) d::put_i32(out, v);
        put_text(out, s.url);
        put_text(out, s.target);
        put_text(out, s.message);
        put_text(out, s.alt);
        d::put_u8(out, s.cell_text_is_html ? 1 : 0);
        put_text(out, s.cell_text);
        d::put_u32(out, s.horizontal_align);
        d::put_u32(out, s.vertical_align);
        for (const std::uint8_t c : s.color) d::put_u8(out, c);
    }
    if (std::any_of(slices.slices.begin(), slices.slices.end(), [](const FileSlice& s) { return s.outsets != std::array<std::int32_t, 4>{}; })) {
        std::vector<std::pair<std::string, d::Writer>> items;
        for (const FileSlice& s : slices.slices) {
            d::Writer w;
            w.integer("sliceID", static_cast<std::int32_t>(s.id));
            w.integer("topOutset", s.outsets[0]);
            w.integer("leftOutset", s.outsets[1]);
            w.integer("bottomOutset", s.outsets[2]);
            w.integer("rightOutset", s.outsets[3]);
            items.emplace_back("slice", std::move(w));
        }
        d::Writer top;
        top.objects("slices", items);
        out += top.versioned("null");
    }
    return out;
}

